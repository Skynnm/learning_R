#### 【纯 R 复现 ggm::pcor (u, S) 核心算法（无第三方包）】偏相关 ####
# 偏相关分析是指在对其他一个或多个定量变量的影响进行控制的条件下，分析两个定量变量之间的相互关系。
# 我们可以使用 ggm 包中的 pcor() 函数计算偏相关系数
# ggm包没有被默认安装，在第一次使用之前需要先进行安装。函数调用格式为：
pcor(u, S)
# 其中 u 是一个数值向量，前两个数值表示要计算相关系数的变量下标，其余的数值为条件变量（即要排除影响的变量）的下标
# s为变量的协方差阵。这个示例有助于阐明用法：
# 复刻 ggm::pcor(u, S)，输入和原版完全一样
my_pcor <- function(u, S){
  # u = c(i,j, cond1, cond2,...)
  i <- u[1]
  j <- u[2]
  cond <- u[-c(1,2)]
  
  # 划分矩阵
  idx_xy <- c(i,j)
  idx_c <- cond
  
  S_xy <- S[idx_xy, idx_xy, drop=FALSE]
  S_xc <- S[idx_xy, idx_c, drop=FALSE]
  S_cc <- S[idx_c, idx_c, drop=FALSE]
  
  # Schur补，求条件协方差矩阵
  inv_Scc <- solve(S_cc)
  S_cond <- S_xy - S_xc %*% inv_Scc %*% t(S_xc)
  
  # 计算偏相关
  pc <- S_cond[1,2] / sqrt(S_cond[1,1] * S_cond[2,2])
  
  # 样本量需要另外传入算p值，ggm的p值需要n
  return(list(estimate = pc))
}

