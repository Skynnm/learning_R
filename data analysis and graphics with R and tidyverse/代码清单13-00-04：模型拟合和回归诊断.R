# 与标准OLS线性模型一样，模型适用性的评价对于广义线性模型也非常重要。
# 但遗憾的是，对于标准的评价过程，统计圈子仍莫衷一是。
# 一般来说，我们可以使用第8章中描述的方法，但要牢记以下建议：


# 当评价模型的适用性时，我们可以绘制初始因变量的预测值与残差的图形。例如，如下代码可绘制一个常见的诊断图：
plot(predict(model, type = "response"),
     residuals(model, type = "deviance"))
# 其中，model为glm()函数的返回值
# R将列出帽子值（hat value）、学生化残差和Cook距离统计量的近似值。
# 不过，对于识别异常点的阈值，现在并没统一答案，它们都是通过相互比较来进行判断，其中一个方法就是绘制各统计量的参考图，然后找出异常大的值。例如，如下代码可创建3幅诊断图：
plot(hatvalues(model))
plot(rstudent(model))
plot(cooks.distance(model))
# 我们还可以用其他方法，代码如下：、
library(car)
influencePlot(model)
# 这段代码可以创建一个综合性的诊断图。
# 在后面的图形中，横轴代表杠杆值，纵轴代表学生化残差值，而绘制的符号大小与Cook距离大小成正比


# 当因变量有许多值时，诊断图非常有用；而当因变量只有有限个值时（比如Logistic回归），诊断图的功效就会降低很多
