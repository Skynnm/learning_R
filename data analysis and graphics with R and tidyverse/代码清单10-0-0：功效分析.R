# 释放天性

# 代码清单10-0-0：功效分析
# 作为统计咨询师，经常被问到这样一个问题：我的研究到底需要多少各受试者呢
# 或者换个说法：对于我的研究，现有 x 个可用的受试者，这样的研究值得做吗
# 这类问题都可通过【功效分析（power analysis）】来解决，它在实验中占有重要地位

# 【功效分析可以帮助在给定置信度的情况下，判断检测到给定效应值所需的样本量】
# 反过来，【它也可以帮助我么在给定置信度的情况下，计算在某样本内能检测到给定效应值的概率】
# 如果概率低得难以接受，修改或者放弃这个实验将是一个明智的选择。

# 在本章中，我么将学习如何对多种统计检验进行功效分析，包括比例检验、t检验、卡方检验、平衡单因素方差分析、相关分析，以及线性模型。
# 由于功效分析针对的是假设检验，我么将首先简单回顾【零假设显著性检验（NHST）过程】，然后学习如何用 R 进行功效分析，主要关注 pwr 包。
# 最后，我们还会学习R中其他可用的功效分析方法。