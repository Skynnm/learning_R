# 我们不妨先看看正太分布的有关函数，以了解这些函数的使用方法。
# 如果不指定一个均值和一个标准差，则函数将假定其为标准正太分布（均值为0，标准差为 1）
# 密度函数（dnorm）、分布函数（pnorm）、分位数函数（qnorm） 和 随机数生成函数（rnorm）的使用见下方：

# （1）在区间[-3, 3]上绘制标准正太曲线：
library(ggplot2)
x <- seq(from = -3, to = 3, by = 0.1)
y <- dnorm(x)
data <- data.frame(x = x, y = y)
ggplot(data, aes(x, y)) +
  geom_line() +
  labs(x = "Normal Deviate",
       y = "Density") +
  scale_x_continuous(
    breaks = seq(-3, 3, 1)
  )

# （2）位于 z = 1.96 左侧的标准正太曲线下方面积是多少？
pnorm(1.96)   # 等于0.975

# （3）均值为500，标准差为100的正太分布的0.9分位点值为多少？
qnorm(0.9, mean = 500, sd = 100)  # 等于628.16

# （4）生成50个均值为50，标准差为10的正太随机数
rnorm(50, mean = 50, sd = 10)
