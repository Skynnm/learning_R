# 数据的标准化：先变成z分数，再拉伸平移到想要的均值M，标准差SD
# 标准化的作用：
# ①消除量纲：不同变量单位不一样，数值大小差距巨大；标准化后放到同一尺度方便比较。
# ②很多算法（主成分、SVM、神经网络）强烈依赖标准化，以不被数值大的主导结果。

