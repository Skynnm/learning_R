# 我们先看看回归系数
coef(fit.reduced)
#(Intercept)           age  yearsmarried religiousness        rating 
# 1.93083017   -0.03527112    0.10062274   -0.32902386   -0.46136144 

# 【在 Logistic 回归中，因变量是 Y=1 的对数优势比（log）】
# 回归系数的含义是当其他自变量不变时，一单位自变量的变化可引起的因变量对数优势比的变化
# 由于对数优势比解释性差，我们可对结果进行指数化
exp(coef(fit.reduced))
#(Intercept)           age  yearsmarried religiousness        rating 
#  6.8952321     0.9653437     1.1058594     0.7196258     0.6304248 

# 可以看到婚龄增加一年，感情危机的优势比将乘以1.106（保持年龄、宗教信仰程度 和 婚姻的自我评分不变）；
# 想反，年龄增加一岁，感情危机优势比则乘以0.965。【已经指数化了】
# 因此，随着婚龄的增加和年龄、宗教信仰程度与对婚姻的自我评分的降低，感情危机优势比将上升。
# 因为自变量不能等于0，截距项在此处没有什么特定含义


# 如果有需要，我们还可以用 confint() 函数获取系数的置信区间。
# 例如，exp(confint(fit.reduced))可在优势比尺度上得到系数95%的置信区间


# 最后，自变量一单位的变化可能并不是我们最想关注的。
# 【对于二值型 Logistic 回归，某自变量 n 单位的变化引起的较高值上优势比的变化为(e^βj)^n，它反映的信息可能更为重要】
# 比如，保持其他自变量不变，婚龄增加一年，感情危机的优势比将乘以1.106，而如果婚龄增加10年，优势比将乘以1.106^10，即2.7