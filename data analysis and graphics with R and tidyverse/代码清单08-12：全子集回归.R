# 代码清单8-12：全子集回归
# 顾名思义，全子集回归是指所有可能的模型都会被检验。
# 分析员可以选择展示所有可能的结果，可以展示 n 个不同子集大小（一个、两个 或 多个自变量）的最佳模型。
# 例如，若 nbest = 2，那么先展示两个最佳的单自变量模型，然后展示两个最佳的双自变量模型，以此类推，以此类推，直到包含所有的自变量。

# 全子集回归可用leaps包中的 regsubsets() 函数来实现。
# 我们可以通过 R平方、调整R平方 或 Mallows Cp统计量等准则来选择最佳模型

# 正如我们所看到的：
# 【R平方的含义是自变量解释因变量的程度】
# 【调整R平方与之类似，但考虑了模型的参数数目】R平方总会随着自变量数目的增加而增加。当与样本量相比，自变量数目很大时，容易导致过拟合。
# R平方很可能会丢失数据的偶然变异信息，而调整R平方则提供了更为真实的总体R平方估计

# 在下列代码清单中，我们对 states 数据集进行了全子集回归。
# leaps 包在一单个图形中展示结果，但是我发现许多人对此感到困惑，以下代码用表格的形式展示了部分结构，我相信这些结果更易于理解

install.packages("leaps")
library("leaps")
states <- as.data.frame(state.x77[,c("Murder", "Population",
                                     "Illiteracy", "Income", "Frost")])
leaps <- regsubsets(Murder ~ Population + Illiteracy + Income +
                   Frost, data = states, nbest = 4)

subsTable <- function(obj, scale) {
  x <- summary(leaps)
  m <- cbind(round(x[[scale]], 3), x$which[, -1])
  colnames(m)[1] <- scale
  m[order(m[,1]), ]
}

subsTable(leaps, scale = "adjr2")
