# 例如
# 只有一个自变量 Income 的模型的调整R平方为0.033
# 具有自变量 Population、Illiteracy 和 Income 的模型的调整R平方为0.539
# 相比之下，只有自变量 Population 和 Illiteracy 的模型的调整 R平方为0.548
# 从本例中可以看到自变量更少的的模型实际拥有更大的调整R平方（对非调整R平方不适用）
# 此表格表明具有两个自变量的模型是最佳模型

# 大部分情况中，全子集回归要优于逐步回归，因为它考虑了更多模型。
# 但是，当有大量自变量时，全子集回归会很慢。
# 一般来说，变量自动选择应该被看作时模型选择的一种辅助方法，而不是直接方法。
# 拟合效果佳而没有意义的模型对我们毫无帮助，对学科背景知识的理解才能最终指引我们获得理想的模型
