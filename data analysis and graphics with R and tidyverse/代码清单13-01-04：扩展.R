# R中扩展的 Logistic 回归和变体如下所示：
# 【】稳健 Logistic 回归：robustbase 包中的glmRob()函数可用拟合稳健的广义线性模型，包括稳健 Logistic 回归。当拟合 Logistic 回归模型数据出现离群点和强影响点时，稳健 Logistic 回归便可派上用场
# 【】多项式 Logistic 回归：若因变量包含两个以上的无序类别（比如，已婚/寡居/离婚），便可使用mlogit包中的mlogit()函数拟合多项式Logistic回归
# 【】序数 Logistic 回归：若因变量是一组有序的类别（比如，信用风险的高/中/低），便可使用 MASS 包中的polyr()函数拟合序数Logistic回归

# 可对多类别的因变量（无论是否有序）进行建模时非常重要的扩展，但它也面临着解释性更复杂的困难。
# 同时，在这种情况下模型拟合优度的评估和回归诊断也变得更为复杂

# 在感情危机的例子中，感情危机的次数被二值化为一个“有/无”的因变量，这是因为我们最感兴趣的是在过去一年中参与者是否有过一次感情危机。
# 如果兴趣转移到量上（过去一年中出现感情危机的次数），便可直接对计数型数据进行分析。
# 分析计数型数据的一种流行方法是泊松回归，者便是我们接下来的话题